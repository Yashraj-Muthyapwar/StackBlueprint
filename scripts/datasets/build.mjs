#!/usr/bin/env node
/**
 * Builds the SQL Flow Lab datasets.
 *
 *   node scripts/datasets/build.mjs [cosmetics_48h|olist|ergast|marvel|sql_lab] [--ergast-source=/path/to/ergast_2024]
 *
 * Reads each configured source (or a cached public source where available),
 * applies only that dataset's documented transformations, and writes:
 *
 *   public/datasets/<id>/<table>.csv.gz          the data the browser fetches
 *   src/.../db/datasets/manifest.generated.ts    schema, keys and row counts
 *
 * The output is committed, so building the app never needs the network.
 */
import { buildErgast } from "./ergast.mjs";
import { buildMarvel } from "./marvel.mjs";
import { buildOlist } from "./olist.mjs";
import { buildCosmetics48h } from "./cosmetics-48h.mjs";
import { buildSqlLab } from "./sql-lab.mjs";
import { writeSource, mb } from "./lib.mjs";

const BUILDERS = {
  cosmetics_48h: buildCosmetics48h,
  ergast: buildErgast,
  marvel: buildMarvel,
  olist: buildOlist,
  sql_lab: buildSqlLab,
};

function emitManifest(results) {
  const body = results
    .map((r) => {
      const tables = r.tables
        .map(
          (t) =>
            `    {\n` +
            `      schema: ${JSON.stringify(t.schema)},\n` +
            `      name: ${JSON.stringify(t.name)},\n` +
            `      file: ${JSON.stringify(t.file)},\n` +
            `      rows: ${t.rows},\n` +
            `      bytes: ${t.bytes},\n` +
            `      primaryKey: ${JSON.stringify(t.primaryKey)},\n` +
            `      columns: [\n` +
            t.columns
              .map(
                (c) =>
                  `        { name: ${JSON.stringify(c.name)}, type: ${JSON.stringify(c.type)}${c.notNull ? ", notNull: true" : ""}${c.defaultValue ? `, defaultValue: ${JSON.stringify(c.defaultValue)}` : ""} },`,
              )
              .join("\n") +
            `\n      ],\n` +
            (t.inlineConstraints?.length
              ? `      inlineConstraints: ${JSON.stringify(t.inlineConstraints)},\n`
              : "") +
            `    },`,
        )
        .join("\n");

      const fks = r.foreignKeys
        .map(
          (f) =>
            `    { fromTable: ${JSON.stringify(f.fromTable)}, fromColumns: ${JSON.stringify(f.fromColumns)}, toTable: ${JSON.stringify(f.toTable)}, toColumns: ${JSON.stringify(f.toColumns)} },`,
        )
        .join("\n");

      return (
        `export const ${r.id.toUpperCase()}_MANIFEST: DatasetManifest = {\n` +
        `  id: ${JSON.stringify(r.id)},\n` +
        `  schemas: ${JSON.stringify(r.schemas)},\n` +
        `  bytes: ${r.bytes},\n` +
        `  tables: [\n${tables}\n  ],\n` +
        `  foreignKeys: [\n${fks}\n  ],\n` +
        (r.setup
          ? `  setup: ${JSON.stringify(r.setup, null, 2).replace(/\n/g, "\n  ")},\n`
          : "") +
        `};`
      );
    })
    .join("\n\n");

  return (
    `// GENERATED by scripts/datasets/build.mjs — do not edit by hand.\n` +
    `// Re-run: node scripts/datasets/build.mjs\n\n` +
    `export interface ManifestColumn {\n` +
    `  name: string;\n  type: string;\n  notNull?: boolean;\n  defaultValue?: string;\n}\n\n` +
    `export interface ManifestTable {\n` +
    `  schema: string;\n  name: string;\n  file: string;\n  rows: number;\n  bytes: number;\n` +
    `  primaryKey: string[];\n  columns: ManifestColumn[];\n  inlineConstraints?: string[];\n}\n\n` +
    `export interface ManifestForeignKey {\n` +
    `  fromTable: string;\n  fromColumns: string[];\n  toTable: string;\n  toColumns: string[];\n}\n\n` +
    `export interface DatasetManifest {\n` +
    `  id: string;\n  schemas: string[];\n  bytes: number;\n` +
    `  tables: ManifestTable[];\n  foreignKeys: ManifestForeignKey[];\n  setup?: { common?: string[]; postgres?: string[]; duckdb?: string[] };\n}\n\n` +
    body +
    `\n`
  );
}

const args = process.argv.slice(2);
// Pass a verified local Kaggle download to preserve the exact public Olist CSVs.
const olistSource = args
  .find((a) => a.startsWith("--olist-source="))
  ?.slice("--olist-source=".length);
const ergastSource = args
  .find((a) => a.startsWith("--ergast-source="))
  ?.slice("--ergast-source=".length);
const marvelSource = args
  .find((a) => a.startsWith("--marvel-source="))
  ?.slice("--marvel-source=".length);
const cosmeticsSource = args
  .find((a) => a.startsWith("--cosmetics-source="))
  ?.slice("--cosmetics-source=".length);
const requested = args.filter((a) => !a.startsWith("--"));
const ids = requested.length ? requested : Object.keys(BUILDERS);
const OPTIONS = {
  cosmetics_48h: { sourceFile: cosmeticsSource },
  ergast: { sourceDir: ergastSource },
  marvel: { sourceDir: marvelSource },
  olist: { sourceDir: olistSource },
};

for (const id of ids) {
  if (!BUILDERS[id]) {
    console.error(`Unknown dataset "${id}". Known: ${Object.keys(BUILDERS).join(", ")}`);
    process.exit(1);
  }
}

// Always rebuild every dataset: the manifest is one file covering all of them,
// and the upstream sources are cached, so a full run costs seconds after the
// first. Naming datasets on the command line only limits what gets re-fetched
// and re-converted in the log; the manifest still needs them all.
if (requested.length && requested.length !== Object.keys(BUILDERS).length) {
  console.log(
    `Note: rebuilding all datasets so the shared manifest stays complete (sources are cached).`,
  );
}

const results = [];
for (const id of Object.keys(BUILDERS)) {
  results.push(await BUILDERS[id](OPTIONS[id]));
}

results.sort((a, b) => a.id.localeCompare(b.id));
await writeSource("manifest.generated.ts", emitManifest(results));

const total = results.reduce((s, r) => s + r.bytes, 0);
console.log(`\n✓ ${results.length} datasets · ${mb(total)} total gzipped`);
console.log(`  data     → public/datasets/`);
console.log(`  manifest → src/components/sql-playground/db/datasets/manifest.generated.ts\n`);
