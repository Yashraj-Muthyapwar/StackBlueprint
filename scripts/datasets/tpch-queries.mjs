#!/usr/bin/env node
/**
 * Regenerates src/components/sql-playground/content/tpch.ts.
 *
 *   node scripts/datasets/tpch-queries.mjs
 *
 * The 22 benchmark queries are read straight out of DuckDB's tpch extension
 * (SELECT query_nr, query FROM tpch_queries()), so the text in the app is the
 * benchmark's, not a hand transcription.
 */
import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(import.meta.url);
// The package restricts its "exports", so resolve the directory rather than a
// subpath and reach into dist/ directly.
const DIST = path.resolve("node_modules/@duckdb/duckdb-wasm/dist");
const duckdb = require(`${DIST}/duckdb-node-blocking.cjs`);

/** Short title and a one-line note for each query. */
const NOTES = {
  1: ["Pricing summary report", "A single big scan with eight aggregates"],
  2: ["Minimum cost supplier", "Correlated subquery picking the cheapest source"],
  3: ["Shipping priority", "Three-way join, then a top-N"],
  4: ["Order priority checking", "EXISTS as a semi-join"],
  5: ["Local supplier volume", "Six tables joined on a region"],
  6: ["Forecasting revenue change", "One table, three range predicates"],
  7: ["Volume shipping", "A self-joined nation pair"],
  8: ["National market share", "Nested aggregation over a derived table"],
  9: ["Product type profit measure", "The heaviest join in the benchmark"],
  10: ["Returned item reporting", "Group by ten columns and rank"],
  11: ["Important stock identification", "HAVING against a scalar subquery"],
  12: ["Shipping modes and order priority", "CASE inside SUM, twice"],
  13: ["Customer distribution", "LEFT JOIN with a NOT LIKE, then a histogram"],
  14: ["Promotion effect", "A ratio of two conditional sums"],
  15: ["Top supplier", "A view feeding a max-of-max lookup"],
  16: ["Parts/supplier relationship", "NOT IN against a subquery"],
  17: ["Small-quantity-order revenue", "Correlated subquery per part"],
  18: ["Large volume customer", "IN against a grouped subquery"],
  19: ["Discounted revenue", "Three OR-ed predicate blocks"],
  20: ["Potential part promotion", "Subqueries nested three deep"],
  21: ["Suppliers who kept orders waiting", "EXISTS and NOT EXISTS on the same table"],
  22: ["Global sales opportunity", "Substring grouping with a scalar subquery"],
};

const GROUPS = [
  ["Q1 to Q6", "Scans, joins and the first correlated subqueries.", [1, 2, 3, 4, 5, 6]],
  ["Q7 to Q12", "Multi-nation joins and conditional aggregation.", [7, 8, 9, 10, 11, 12]],
  ["Q13 to Q18", "Outer joins, views and grouped subqueries.", [13, 14, 15, 16, 17, 18]],
  ["Q19 to Q22", "The awkward ones. Optimisers earn their keep here.", [19, 20, 21, 22]],
];

const TABLES = [
  "lineitem",
  "orders",
  "partsupp",
  "part",
  "customer",
  "supplier",
  "nation",
  "region",
];

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const db = await duckdb.createDuckDB(
  {
    mvp: { mainModule: path.join(DIST, "duckdb-mvp.wasm"), mainWorker: null },
    eh: { mainModule: path.join(DIST, "duckdb-eh.wasm"), mainWorker: null },
  },
  new duckdb.VoidLogger(),
  duckdb.NODE_RUNTIME,
);
await db.instantiate(() => {});
const conn = db.connect();
conn.query("INSTALL tpch");
conn.query("LOAD tpch");
const queries = conn
  .query("SELECT query_nr, query FROM tpch_queries() ORDER BY query_nr")
  .toArray()
  .map((r) => r.toJSON())
  .map((r) => ({ n: Number(r.query_nr), sql: String(r.query).trimEnd() }));

let out = `import type { ExampleGroup } from "./types";

/**
 * The 22 official TPC-H queries, exactly as DuckDB's tpch extension ships them.
 *
 * GENERATED by scripts/datasets/tpch-queries.mjs — do not hand-edit the query
 * bodies; they are the benchmark's text, not our prose.
 */
export const TPCH_EXAMPLES: ExampleGroup[] = [
  {
    group: "Getting oriented",
    blurb: "Eight tables in the classic snowflake. Start by looking at them.",
    items: [
      {
        title: "The schema",
        note: "Row counts for all eight tables",
        sql: \`${TABLES.map((t, i) =>
          i === 0
            ? `SELECT '${t}' AS t, count(*) AS rows FROM ${t}`
            : `UNION ALL SELECT '${t}', count(*) FROM ${t}`,
        ).join("\n")}
ORDER BY rows DESC;\`,
      },
      {
        title: "Profile the fact table",
        note: "SUMMARIZE every lineitem column",
        sql: \`SUMMARIZE lineitem;\`,
      },
      {
        title: "Turn the scale up",
        note: "Regenerate with more rows, then re-run Q1",
        sql: \`-- dbgen appends to whatever is already there, so clear the tables
-- first or the row counts compound each time you run this.
-- DuckDB drops one object per statement, hence the list.
${TABLES.map((t) => `DROP TABLE IF EXISTS ${t};`).join("\n")}

CALL dbgen(sf = 0.2);
SELECT count(*) AS lineitems FROM lineitem;\`,
      },
    ],
  },
`;

for (const [group, blurb, nums] of GROUPS) {
  out += `  {\n    group: ${JSON.stringify(group)},\n    blurb: ${JSON.stringify(blurb)},\n    items: [\n`;
  for (const n of nums) {
    const q = queries.find((x) => x.n === n);
    const [title, note] = NOTES[n];
    out +=
      `      {\n` +
      `        title: ${JSON.stringify(`Q${n}. ${title}`)},\n` +
      `        note: ${JSON.stringify(note)},\n` +
      `        sql: \`${esc(q.sql)}\`,\n` +
      `      },\n`;
  }
  out += `    ],\n  },\n`;
}
out += `];\n`;

const target = "src/components/sql-playground/content/tpch.ts";
await writeFile(target, out);
console.log(`✓ ${queries.length} TPC-H queries → ${target}`);
