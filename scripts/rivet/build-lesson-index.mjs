#!/usr/bin/env node
/**
 * Works out which lessons actually have content, so Rivet only ever links to
 * real lessons.
 *
 * It runs by itself in three places, so nobody has to remember it:
 *   - `npm run dev`    when the dev server starts, and again whenever a file under
 *                      src/lessons is added, changed or removed (Vite plugin below)
 *   - `npm run build`  at the start of the build (same plugin)
 *   - `npm run rivet:lessons`  by hand, if you ever want to run it on its own
 *
 * It reads every TypeScript file under src/lessons without executing it, finds each
 * lesson object (an object with a string `slug` and a `sections` property) and
 * records its track and slug when `sections` is not the literal empty array.
 * Placeholder lessons (`sections: []`, see AGENTS.md) are left out. If a slug is
 * a placeholder anywhere in the same track it is treated as unavailable too, so a
 * repeated slug can never make an empty lesson look real.
 *
 * Writes src/lib/rivet/available-lessons.generated.ts: a sorted list of
 * "track/slug" strings. The file is committed, and only rewritten when the list
 * actually changes (so it never causes needless reloads).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("../../", import.meta.url));
const lessonsDir = join(root, "src/lessons");
const outFile = join(root, "src/lib/rivet/available-lessons.generated.ts");

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (name.endsWith(".ts") && !name.endsWith(".d.ts")) yield full;
  }
}

// Property names may be bare (slug) or quoted ("slug") depending on how the file was written.
const propName = (p) =>
  ts.isPropertyAssignment(p) && (ts.isIdentifier(p.name) || ts.isStringLiteralLike(p.name))
    ? p.name.text
    : undefined;

const findProp = (obj, name) => obj.properties.find((p) => propName(p) === name);

const stringProp = (obj, name) => {
  const p = findProp(obj, name);
  return p && ts.isStringLiteralLike(p.initializer) ? p.initializer.text : undefined;
};

const sectionsProp = (obj) => findProp(obj, "sections");

/** Scans src/lessons and rewrites the generated file if the list changed. */
export function generateLessonIndex() {
  const withContent = new Set();
  const placeholders = new Set();

  for (const file of walk(lessonsDir)) {
    const parts = relative(lessonsDir, file).split(sep);
    if (parts.length < 2) continue; // top-level files (roadmap.ts, types.ts) describe lessons, they are not lessons
    const track = parts[0];
    const source = ts.createSourceFile(
      file,
      readFileSync(file, "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );
    const visit = (node) => {
      if (ts.isObjectLiteralExpression(node)) {
        const slug = stringProp(node, "slug");
        const sections = sectionsProp(node);
        if (slug && sections) {
          const empty =
            ts.isArrayLiteralExpression(sections.initializer) &&
            sections.initializer.elements.length === 0;
          (empty ? placeholders : withContent).add(`${track}/${slug}`);
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(source);
  }

  const available = [...withContent].filter((key) => !placeholders.has(key)).sort();
  const body = available.map((key) => `  ${JSON.stringify(key)},`).join("\n");
  const output = `// Generated by scripts/rivet/build-lesson-index.mjs. Do not edit by hand.\n// Lessons that have content, as "track/slug". Placeholders are left out.\nexport const AVAILABLE_LESSONS: readonly string[] = [\n${body}\n];\n`;

  const changed = !existsSync(outFile) || readFileSync(outFile, "utf8") !== output;
  if (changed) writeFileSync(outFile, output);
  return { available: available.length, placeholders: placeholders.size, changed };
}

/** Vite plugin: regenerate on dev-server start, on build start, and whenever a lesson file changes. */
export function rivetLessonIndex() {
  const run = (why) => {
    try {
      const { available, placeholders, changed } = generateLessonIndex();
      if (changed) {
        console.log(
          `[rivet] lesson index updated (${why}): ${available} lessons with content, ${placeholders} placeholders`,
        );
      }
    } catch (error) {
      console.warn("[rivet] could not update the lesson index:", error);
    }
  };

  return {
    name: "rivet-lesson-index",
    buildStart() {
      run("start");
    },
    configureServer(server) {
      let timer;
      const onFileEvent = (file) => {
        if (!file.startsWith(lessonsDir) || !file.endsWith(".ts")) return;
        clearTimeout(timer);
        timer = setTimeout(() => run("lesson file changed"), 200);
      };
      server.watcher.on("change", onFileEvent);
      server.watcher.on("add", onFileEvent);
      server.watcher.on("unlink", onFileEvent);
    },
  };
}

// Run directly: `node scripts/rivet/build-lesson-index.mjs`
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { available, placeholders, changed } = generateLessonIndex();
  console.log(
    `${available} lessons with content, ${placeholders} placeholders -> ${relative(root, outFile)}${changed ? " (updated)" : " (unchanged)"}`,
  );
}
